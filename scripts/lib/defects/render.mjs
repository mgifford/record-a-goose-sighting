export function renderAll (registry, coverage, options = {}) {
  return new Map([
    [REGISTRY_PATH, renderRegistryJson(registry)],
    [COVERAGE_PATH, `${JSON.stringify(coverage, null, 2)}\n`],
    [MARKDOWN_PATH, renderMarkdown(registry, options)],
    [COVERAGE_MARKDOWN_PATH, renderCoverageMarkdown(coverage)]
  ])
}
