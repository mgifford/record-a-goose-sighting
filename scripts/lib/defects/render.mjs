function optionList (values, label) {
  return `<option value="">All ${escapeHtml(label)}</option>` +
    values.map((value) => `<option value="${escapeHtml(value)}">${escapeHtml(value)}</option>`).join('')
}

function card (defect, base) {
  const url = `${base}${defect.url}`
  const controls = defect.controlFixtureId
    ? `<a href="#defect-${escapeHtml(defect.controlFixtureId)}">${escapeHtml(defect.controlFixtureId)}</a>`
    : (defect.relatedElements.filter((element) => element.purpose === 'comparison-control')
        .map((element) => escapeHtml(element.css || element.role || element.note || 'control'))
        .join(', ') || 'None recorded')
  const interaction = defect.interactionSteps.length > 0
    ? defect.interactionSteps.map((step) => `${step.action}${step.selector ? ` ${step.selector}` : ''}`).join('; ')
    : 'None'

  return `<article class="catalogue-card" id="defect-${escapeHtml(defect.id)}" data-service="${escapeHtml(defect.service)}" data-category="${escapeHtml(defect.category)}" data-classification="${escapeHtml(defect.classification)}" data-lifecycle="${escapeHtml(defect.reviewStatus.lifecycle)}" data-capability="${escapeHtml(defect.affectedCapabilities.join(' '))}" data-detection="${escapeHtml(defect.detection.expectedMethods.join(' '))}" data-wcag="${escapeHtml(defect.wcag.map((mapping) => mapping.criterion).join(' '))}" data-act="${escapeHtml(defect.actRules.map((mapping) => mapping.ruleId).join(' '))}" data-interaction="${defect.interactionSteps.length > 0 ? 'required' : 'none'}">
  <h3 id="${escapeHtml(defect.id)}">${escapeHtml(defect.title)} <span class="defect-id">${escapeHtml(defect.id)}</span></h3>
  <p class="catalogue-description">${escapeHtml(defect.description)}</p>
  <dl class="catalogue-meta">
    <dt>Page</dt><dd><a href="${escapeHtml(url)}">${escapeHtml(defect.url)}</a></dd>
    <dt>Component</dt><dd>${escapeHtml(defect.component || 'Not recorded')}</dd>
    <dt>Category</dt><dd>${escapeHtml(defect.category)}</dd>
    <dt>Classification</dt><dd>${escapeHtml(defect.classification)}</dd>
    <dt>WCAG</dt><dd>${defect.wcag.length === 0 ? 'No mapping recorded' : defect.wcag.map((mapping) => `${escapeHtml(mapping.criterion)} (${escapeHtml(mapping.status)})`).join(', ')}</dd>
    <dt>ACT rules</dt><dd>${defect.actRules.length === 0 ? 'Not an ACT case' : defect.actRules.map((mapping) => `${escapeHtml(mapping.ruleId)} (${escapeHtml(mapping.status)})`).join(', ')}</dd>
    <dt>Locators</dt><dd><ul class="locators">${defect.locators.map((locator) => `<li>${escapeHtml(locatorLabel(locator))}</li>`).join('')}</ul></dd>
    <dt>Interaction</dt><dd>${escapeHtml(interaction)}</dd>
    <dt>Expected</dt><dd>${escapeHtml(defect.expectedBehaviour)}</dd>
    <dt>Actual</dt><dd>${escapeHtml(defect.actualBehaviour)}</dd>
    <dt>User impact</dt><dd>${escapeHtml(defect.userImpact)}</dd>
    <dt>Affects</dt><dd>${escapeHtml(defect.affectedCapabilities.join(', ') || 'Not recorded')}</dd>
    <dt>Detection</dt><dd>${escapeHtml(defect.detection.expectedMethods.join(', ') || 'Not recorded')}${defect.detection.observed.length > 0 ? `<br>Observed: ${escapeHtml(defect.detection.observed.map((observation) => `${observation.engine} ${observation.engineVersion || ''} ${observation.result}${observation.ruleId ? ` (${observation.ruleId})` : ''} on ${observation.date}`).join('; '))}` : ''}</dd>
    <dt>Manual test</dt><dd>${escapeHtml(defect.manualTests.join(' ') || 'Not recorded')}</dd>
    <dt>Review</dt><dd>${escapeHtml(reviewLabel(defect.reviewStatus))}</dd>
    <dt>Comparison control</dt><dd>${controls}</dd>
    <dt>Evidence</dt><dd>${escapeHtml([...defect.evidence.assertions, ...defect.evidence.tests].join(' ') || 'Not recorded')}</dd>
  </dl>
</article>`
}

