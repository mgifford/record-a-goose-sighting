export const DEFAULT_SITE_URL = 'https://mgifford.github.io/record-a-goose-sighting/'
export const DEFAULT_BASE = '/record-a-goose-sighting/'

export function normalizeBase (value = process.env.SITE_BASE || DEFAULT_BASE) {
  const inner = String(value || '/').replace(/^\/+|\/+$/g, '')
  return inner === '' ? '/' : `/${inner}/`
}

export function normalizeSiteUrl (value = process.env.SITE_URL || DEFAULT_SITE_URL) {
  return `${String(value).replace(/\/+$/, '')}/`
}

function escapeHtml (value) {
  return String(value ?? '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
}

function escapeMarkdown (value) {
  return String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ')
}

function code (value) {
  return `\`${String(value).replaceAll('`', "'")}\``
}

function joinOrNone (values, formatter = (value) => value) {
  return values.length === 0 ? 'none' : values.map(formatter).join('; ')
}

function answerKeyNumber (defect) {
  const alias = defect.aliases.find((value) => value.startsWith('answer-key:'))
  return alias ? Number(alias.split(':')[1]) : null
}

export function compareDefects (first, second) {
  const firstKey = answerKeyNumber(first)
  const secondKey = answerKeyNumber(second)
  if (firstKey !== null && secondKey !== null) return firstKey - secondKey
  if (firstKey !== null) return -1
  if (secondKey !== null) return 1
  return first.id.localeCompare(second.id)
}

export function defectUrl (defect, siteUrl = normalizeSiteUrl()) {
  return `${siteUrl}${defect.url}${defect.fragment ? `#${defect.fragment}` : ''}`
}

function locatorLabel (locator) {
  const parts = [locator.type]
  if (locator.role) parts.push(locator.role)
  if (locator.name) parts.push(`"${locator.name}"`)
  if (locator.value) parts.push(code(locator.value))
  if (locator.framePath?.length) parts.push(`frame: ${locator.framePath.join(' > ')}`)
  if (locator.shadowPath?.length) parts.push(`shadow: ${locator.shadowPath.join(' > ')}`)
  if (locator.note) parts.push(locator.note)
  return parts.join(' ')
}

function comparisonControlLabel (defect) {
  if (defect.controlFixtureId) return code(defect.controlFixtureId)
  const controls = defect.relatedElements.filter((element) => element.purpose === 'comparison-control')
  if (controls.length === 0) return 'none recorded'
  return controls.map((element) => `${code(element.css || element.role || element.note || 'control')}${element.note ? ` (${escapeMarkdown(element.note)})` : ''}`).join('; ')
}

function wcagLabel (mapping) {
  return `${mapping.criterion} (${mapping.status})`
}

function actLabel (mapping) {
  return `${mapping.ruleId} ${mapping.status}`
}

function reviewLabel (reviewStatus) {
  const dimensions = Object.entries(reviewStatus.dimensions)
    .map(([key, value]) => `${key}: ${value}`)
    .join(', ')
  return `${reviewStatus.lifecycle} (${dimensions})`
}

export function renderRegistryJson (registry) {
  return `${JSON.stringify(registry, null, 2)}\n`
}

export function renderMarkdown (registry, { siteUrl = normalizeSiteUrl() } = {}) {
  const lines = []
  lines.push('# Known defects')
  lines.push('')
  lines.push('<!-- Generated by `npm run defects:generate` from the authoritative source records. Do not edit this file by hand. -->')
  lines.push('')
  lines.push('Canonical machine-readable registry: [`data/known-defects.json`](../data/known-defects.json).')
  lines.push('')
  lines.push('This is the answer key. It is not part of a blind evaluation, and an entry here is a declared')
  lines.push('defect with a stated expected outcome, not proof that a person has experienced the barrier.')
  lines.push('')
  lines.push(`The registry describes **${registry.counts.defects} defects** across ${Object.keys(registry.counts.byService).length} services.`)
  lines.push('')
  lines.push('An expected outcome is a hypothesis until the review dimensions show an independent review.')
  lines.push('')
  lines.push('## Coverage at a glance')
  lines.push('')
  lines.push('| Dimension | Count |')
  lines.push('| :--- | ---: |')
  lines.push(`| Defects | ${registry.counts.defects} |`)
  for (const [service, count] of Object.entries(registry.counts.byService)) {
    lines.push(`| Service: ${escapeMarkdown(service)} | ${count} |`)
  }
  for (const [classification, count] of Object.entries(registry.counts.byClassification)) {
    lines.push(`| Classification: ${escapeMarkdown(classification)} | ${count} |`)
  }
  lines.push('')
  lines.push('See [DEFECT-COVERAGE.md](DEFECT-COVERAGE.md) for WCAG, ACT, capability, detection and')
  lines.push('assistive-technology matrices.')
  lines.push('')
  lines.push('## Sources')
  lines.push('')
  lines.push('The registry is generated from these files. Each digest is the SHA-256 of the committed source.')
  lines.push('')
  lines.push('| Source | Kind | SHA-256 |')
  lines.push('| :--- | :--- | :--- |')
  for (const source of registry.sources) {
    lines.push(`| ${code(source.path)} | ${escapeMarkdown(source.kind)} | ${code(source.sha256)} |`)
  }
  lines.push('')

  const services = [...new Set(registry.defects.map((defect) => defect.service))]
  for (const service of services) {
    const defects = registry.defects.filter((defect) => defect.service === service).sort(compareDefects)
    lines.push(`## Service: ${escapeMarkdown(service)} (${defects.length})`)
    lines.push('')

    for (const defect of defects) {
      lines.push(`### ${code(defect.id)} ${escapeMarkdown(defect.title)}`)
      lines.push('')
      lines.push(`- **Page:** [${escapeMarkdown(defect.url)}](${defectUrl(defect, siteUrl)})`)
      if (defect.fixtureId) lines.push(`- **Fixture:** ${code(defect.fixtureId)}`)
      if (defect.component) lines.push(`- **Component:** ${escapeMarkdown(defect.component)}`)
      lines.push(`- **Category:** ${escapeMarkdown(defect.category)}`)
      lines.push(`- **Classification:** ${escapeMarkdown(defect.classification)}`)
      lines.push(`- **WCAG:** ${joinOrNone(defect.wcag, wcagLabel)}`)
      lines.push(`- **ACT rules:** ${joinOrNone(defect.actRules, actLabel)}`)
      lines.push(`- **Locators:** ${joinOrNone(defect.locators, locatorLabel)}`)
      lines.push(`- **Preconditions:** ${joinOrNone(defect.preconditions, escapeMarkdown)}`)
      lines.push(`- **Interaction:** ${joinOrNone(defect.interactionSteps, (step) => `${step.action}${step.selector ? ` ${code(step.selector)}` : ''}${step.key ? ` ${code(step.key)}` : ''}`)}`)
      lines.push(`- **Expected behaviour:** ${escapeMarkdown(defect.expectedBehaviour)}`)
      lines.push(`- **Actual behaviour:** ${escapeMarkdown(defect.actualBehaviour)}`)
      lines.push(`- **User impact:** ${escapeMarkdown(defect.userImpact)}`)
      lines.push(`- **Affected capabilities:** ${joinOrNone(defect.affectedCapabilities, escapeMarkdown)}`)
      lines.push(`- **Detection:** ${joinOrNone(defect.detection.expectedMethods, escapeMarkdown)}${defect.detection.note ? `. ${escapeMarkdown(defect.detection.note)}` : ''}`)
      lines.push(`- **Manual test:** ${joinOrNone(defect.manualTests, escapeMarkdown)}`)
      if (defect.assistiveTechnologyTests.length > 0) {
        lines.push(`- **Assistive technology:** ${joinOrNone(defect.assistiveTechnologyTests, (test) => `${escapeMarkdown(test.platform)} / ${escapeMarkdown(test.browser)} / ${escapeMarkdown(test.assistiveTechnology)}: ${test.status}`)}`)
      }
      if (defect.detection.observed.length > 0) {
        lines.push(`- **Engine observations:** ${joinOrNone(defect.detection.observed, (observation) => `${observation.engine}${observation.engineVersion ? ` ${observation.engineVersion}` : ''} ${observation.result}${observation.ruleId ? ` (${observation.ruleId})` : ''} on ${observation.date}`)}`)
      }
      lines.push(`- **Review:** ${reviewLabel(defect.reviewStatus)}`)
      if (defect.reviewStatus.note) lines.push(`- **Review note:** ${escapeMarkdown(defect.reviewStatus.note)}`)
      lines.push(`- **Comparison control:** ${comparisonControlLabel(defect)}`)
      lines.push(`- **Evidence:** ${joinOrNone([...defect.evidence.assertions, ...defect.evidence.tests, ...defect.evidence.artifacts], escapeMarkdown)}`)
      lines.push(`- **Sources:** ${joinOrNone(defect.sources, (source) => `[${escapeMarkdown(source.title)}](${source.url})`)}`)
      lines.push(`- **Provenance:** ${defect.provenance.origin} from ${defect.provenance.derivedFrom.map((file) => code(file)).join(', ')}`)
      if (defect.notApplicable.length > 0) {
        lines.push(`- **Not applicable:** ${defect.notApplicable.map((field) => code(field)).join(', ')}`)
      }
      lines.push('')
    }
  }

  return `${lines.join('\n').replace(/\n+$/, '')}\n`
}

function table (lines, heading, counts, label) {
  lines.push(`## ${heading}`)
  lines.push('')
  if (Object.keys(counts).length === 0) {
    lines.push('No defects represent this dimension.')
    lines.push('')
    return
  }
  lines.push(`| ${label} | Defects |`)
  lines.push('| :--- | ---: |')
  for (const [key, value] of Object.entries(counts)) {
    lines.push(`| ${escapeMarkdown(key)} | ${value} |`)
  }
  lines.push('')
}

