export function renderCoverageMarkdown (coverage) {
  const lines = []
  lines.push('# Defect coverage')
  lines.push('')
  lines.push('<!-- Generated by `npm run defects:generate`. Do not edit this file by hand. -->')
  lines.push('')
  lines.push('Generated from [`data/known-defects.json`](../data/known-defects.json). Machine-readable form:')
  lines.push('[`data/defect-coverage.json`](../data/defect-coverage.json).')
  lines.push('')
  lines.push('> Coverage counts **declared defects**, not WCAG success criteria achieved. ACT rule coverage is')
  lines.push('> not WCAG coverage, and a clean automated scan is not a conformance claim.')
  lines.push('')
  lines.push('## Totals')
  lines.push('')
  lines.push('| Measure | Value |')
  lines.push('| :--- | ---: |')
  for (const [key, value] of Object.entries(coverage.totals)) {
    lines.push(`| ${escapeMarkdown(TOTAL_LABELS[key] || key)} | ${value} |`)
  }
  lines.push('')
  table(lines, 'Defects by service', coverage.byService, 'Service')
  table(lines, 'Defects by category', coverage.byCategory, 'Category')
  table(lines, 'Defects by classification', coverage.byClassification, 'Classification')
  table(lines, 'Defects by review lifecycle', coverage.byReviewLifecycle, 'Lifecycle')
  table(lines, 'Defects by affected capability', coverage.byCapability, 'Capability')
  table(lines, 'Defects by expected detection method', coverage.byDetectionMethod, 'Detection method')
  table(lines, 'Defects by WCAG criterion', coverage.byWcagCriterion, 'Criterion')
  table(lines, 'WCAG mapping status', coverage.byWcagStatus, 'Status')
  table(lines, 'Defects by ACT rule', coverage.byActRule, 'ACT rule')
  table(lines, 'Defects by source framework', coverage.byFramework, 'Framework')
  table(lines, 'Interaction dependence', coverage.byInteraction, 'Interaction')
  table(lines, 'Comparison controls', coverage.byControl, 'Control coverage')

  lines.push('## Review dimensions')
  lines.push('')
  lines.push('| Dimension | Status | Defects |')
  lines.push('| :--- | :--- | ---: |')
  for (const [dimension, counts] of Object.entries(coverage.reviewDimensions)) {
    for (const [status, value] of Object.entries(counts)) {
      lines.push(`| ${escapeMarkdown(dimension)} | ${escapeMarkdown(status)} | ${value} |`)
    }
  }
  lines.push('')
  lines.push('## Assistive-technology coverage')
  lines.push('')
  lines.push(`Recorded procedures: **${coverage.assistiveTechnology.tests}** across **${coverage.assistiveTechnology.defects}** defects.`)
  lines.push('')
  if (Object.keys(coverage.assistiveTechnology.byStatus).length > 0) {
    lines.push('| Status | Count |')
    lines.push('| :--- | ---: |')
    for (const [status, value] of Object.entries(coverage.assistiveTechnology.byStatus)) {
      lines.push(`| ${escapeMarkdown(status)} | ${value} |`)
    }
    lines.push('')
  }
  if (Object.keys(coverage.assistiveTechnology.byEnvironment).length > 0) {
    lines.push('| Environment | Procedures |')
    lines.push('| :--- | ---: |')
    for (const [environment, value] of Object.entries(coverage.assistiveTechnology.byEnvironment)) {
      lines.push(`| ${escapeMarkdown(environment)} | ${value} |`)
    }
    lines.push('')
  }
  lines.push('No screen-reader output is recorded as observed until a person has run the procedure.')
  lines.push('')

  return `${lines.join('\n').replace(/\n+$/, '')}\n`
}

