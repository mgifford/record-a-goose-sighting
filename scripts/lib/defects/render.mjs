/**
 * Renders every generated representation of the defect registry: the
 * committed JSON, the generated Markdown, the coverage matrices, the public
 * answer-key catalogue and the published manifest consumed by Open Scans.
 *
 * All output is deterministic: no timestamps, stable ordering, stable
 * whitespace. `defects:check-sync` compares regenerated output with the
 * committed files byte for byte.
 */
